<?php

declare(strict_types=1);

namespace Noria\Keel\Db;

use Illuminate\Database\Schema\Blueprint;
use Illuminate\Database\Schema\ColumnDefinition;
use Illuminate\Support\Facades\Config;
use Illuminate\Support\Str;
use InvalidArgumentException;

enum KeyType: string
{
    case Uuid = 'uuid';
    case Ulid = 'ulid';
    case Int = 'int';
    case String = 'string';

    public static function forModels(): self
    {
        $type = self::configured('keel.key_type');

        if ($type === self::String) {
            throw new InvalidArgumentException('keel.key_type must be uuid, ulid or int: Keel cannot generate a string key.');
        }

        return $type;
    }

    public static function forTenants(): self
    {
        return self::configured('keel.tenancy.key_type');
    }

    private static function configured(string $key): self
    {
        $value = Config::string($key, self::Uuid->value);

        return self::tryFrom($value)
            ?? throw new InvalidArgumentException("{$key} must be one of uuid, ulid, int or string, not {$value}.");
    }

    public function generates(): bool
    {
        return $this === self::Uuid || $this === self::Ulid;
    }

    public function newId(): string
    {
        return match ($this) {
            self::Uuid => (string) Str::uuid7(),
            self::Ulid => strtolower((string) Str::ulid()),
            self::Int, self::String => throw new InvalidArgumentException("A {$this->value} key is not generated by Keel."),
        };
    }

    public function accepts(mixed $value): bool
    {
        if (is_int($value)) {
            return $this === self::Int && $value > 0;
        }

        if (! is_string($value)) {
            return false;
        }

        return match ($this) {
            self::Uuid => Str::isUuid($value),
            self::Ulid => Str::isUlid($value),
            self::Int => preg_match('/^[1-9][0-9]{0,18}$/', $value) === 1,
            self::String => preg_match('/^[A-Za-z0-9._-]{1,64}$/', $value) === 1,
        };
    }

    public function normalise(string $value): string
    {
        return $this === self::Uuid || $this === self::Ulid ? strtolower($value) : $value;
    }

    public function primary(Blueprint $table, string $column = 'id'): void
    {
        match ($this) {
            self::Uuid => $table->uuid($column)->primary(),
            self::Ulid => $table->ulid($column)->primary(),
            self::Int => $table->id($column),
            self::String => $table->string($column, 64)->primary(),
        };
    }

    public function column(Blueprint $table, string $column): ColumnDefinition
    {
        return match ($this) {
            self::Uuid => $table->uuid($column),
            self::Ulid => $table->ulid($column),
            self::Int => $table->unsignedBigInteger($column),
            self::String => $table->string($column, 64),
        };
    }

    public function postgresType(): string
    {
        return match ($this) {
            self::Uuid => 'uuid',
            self::Int => 'bigint',
            self::Ulid, self::String => 'text',
        };
    }
}
